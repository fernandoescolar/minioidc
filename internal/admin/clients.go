package admin

import (
	"crypto"
	"net/http"
	"net/url"
	"strings"

	"github.com/fernandoescolar/minioidc/pkg/cryptography"
	"github.com/fernandoescolar/minioidc/pkg/domain"
)

type clientDTO struct {
	ID                      string   `json:"id"`
	TokenEndpointAuthMethod string   `json:"token_endpoint_auth_method"`
	RedirectURIs            []string `json:"redirect_uris"`
	PostLogoutRedirectURIs  []string `json:"post_logout_redirect_uris"`
	JWKSURI                 string   `json:"jwks_uri"`
	PublicKeys              []string `json:"public_keys"`
	GrantTypes              []string `json:"grant_types"`
	HasSecret               bool     `json:"has_secret"`
	// Secret is only returned once: when it is generated
	Secret string `json:"secret,omitempty"`
}

// clientInput is the body to create or update a client. The secrets are
// always generated by the server.
type clientInput struct {
	ID                      string   `json:"id"`
	TokenEndpointAuthMethod string   `json:"token_endpoint_auth_method"`
	RedirectURIs            []string `json:"redirect_uris"`
	PostLogoutRedirectURIs  []string `json:"post_logout_redirect_uris"`
	JWKSURI                 string   `json:"jwks_uri"`
	PublicKeys              []string `json:"public_keys"`
	GrantTypes              []string `json:"grant_types"`
}

func clientToDTO(data domain.ClientData) clientDTO {
	keys := []string{}
	for _, key := range data.PublicKeys {
		if encoded, err := cryptography.EncodePublicKeyPEM(key); err == nil {
			keys = append(keys, encoded)
		}
	}

	return clientDTO{
		ID:                      data.ID,
		TokenEndpointAuthMethod: data.TokenEndpointAuthMethod,
		RedirectURIs:            nonNil(data.RedirectURIs),
		PostLogoutRedirectURIs:  nonNil(data.PostLogoutRedirectURIs),
		JWKSURI:                 data.JWKSURI,
		PublicKeys:              keys,
		GrantTypes:              grantTypes(data),
		HasSecret:               data.SecretHash != "" || data.Secret != "",
	}
}

// secretKind returns which secret the authentication method needs
func secretKind(method string) (hashed, plain bool) {
	switch method {
	case "", domain.AuthMethodClientSecretBasic, domain.AuthMethodClientSecretPost:
		return true, false
	case domain.AuthMethodClientSecretJWT:
		return false, true
	default:
		return false, false
	}
}

func (h *Handler) listClients(w http.ResponseWriter, _ *http.Request) {
	clients, err := h.clients.ListClients()
	if err != nil {
		writeInternalError(w, err)
		return
	}

	result := make([]clientDTO, 0, len(clients))
	for _, c := range clients {
		result = append(result, clientToDTO(c))
	}

	writeJSON(w, http.StatusOK, result)
}

func (h *Handler) findClient(w http.ResponseWriter, r *http.Request) (domain.ClientData, bool) {
	client, err := h.clients.GetClientByID(r.PathValue("id"))
	if err != nil {
		writeError(w, http.StatusNotFound, "client not found")
		return domain.ClientData{}, false
	}

	return client.Data(), true
}

func (h *Handler) getClient(w http.ResponseWriter, r *http.Request) {
	if data, ok := h.findClient(w, r); ok {
		writeJSON(w, http.StatusOK, clientToDTO(data))
	}
}

func (h *Handler) createClient(w http.ResponseWriter, r *http.Request) {
	var input clientInput
	if !readJSON(w, r, &input) {
		return
	}

	input.ID = strings.TrimSpace(input.ID)
	if _, err := h.clients.GetClientByID(input.ID); err == nil {
		writeError(w, http.StatusConflict, "a client with this id already exists")
		return
	}

	data, ok := h.clientData(w, input)
	if !ok {
		return
	}

	secret, ok := h.ensureSecret(w, &data, false)
	if !ok {
		return
	}

	if _, err := h.clients.NewClient(data); err != nil {
		writeStoreError(w, err)
		return
	}

	dto := clientToDTO(data)
	dto.Secret = secret
	writeJSON(w, http.StatusCreated, dto)
}

func (h *Handler) updateClient(w http.ResponseWriter, r *http.Request) {
	current, ok := h.findClient(w, r)
	if !ok {
		return
	}

	var input clientInput
	if !readJSON(w, r, &input) {
		return
	}

	input.ID = current.ID
	data, ok := h.clientData(w, input)
	if !ok {
		return
	}

	// the secret is kept if the new authentication method uses the same kind of secret
	data.SecretHash, data.Secret = current.SecretHash, current.Secret
	secret, ok := h.ensureSecret(w, &data, false)
	if !ok {
		return
	}

	if err := h.clients.UpdateClient(data); err != nil {
		writeStoreError(w, err)
		return
	}

	dto := clientToDTO(data)
	dto.Secret = secret
	writeJSON(w, http.StatusOK, dto)
}

func (h *Handler) rotateClientSecret(w http.ResponseWriter, r *http.Request) {
	data, ok := h.findClient(w, r)
	if !ok {
		return
	}

	if hashed, plain := secretKind(data.TokenEndpointAuthMethod); !hashed && !plain {
		writeError(w, http.StatusBadRequest, "the authentication method of the client does not use a secret")
		return
	}

	secret, ok := h.ensureSecret(w, &data, true)
	if !ok {
		return
	}

	if err := h.clients.UpdateClient(data); err != nil {
		writeStoreError(w, err)
		return
	}

	dto := clientToDTO(data)
	dto.Secret = secret
	writeJSON(w, http.StatusOK, dto)
}

// ensureSecret removes the secrets the authentication method does not use and
// generates the missing one (or a new one when rotate is true). It returns the
// generated secret, that is only shown once.
func (h *Handler) ensureSecret(w http.ResponseWriter, data *domain.ClientData, rotate bool) (string, bool) {
	hashed, plain := secretKind(data.TokenEndpointAuthMethod)
	if !hashed {
		data.SecretHash = ""
	}
	if !plain {
		data.Secret = ""
	}

	missing := (hashed && data.SecretHash == "") || (plain && data.Secret == "")
	if !rotate && !missing {
		return "", true
	}

	secret, err := cryptography.RandomToken()
	if err != nil {
		writeInternalError(w, err)
		return "", false
	}

	if hashed {
		if data.SecretHash, err = cryptography.HashPassword(secret); err != nil {
			writeInternalError(w, err)
			return "", false
		}
	}
	if plain {
		data.Secret = secret
	}

	return secret, true
}

// clientData validates the input: URLs, public keys and authentication method
func (h *Handler) clientData(w http.ResponseWriter, input clientInput) (domain.ClientData, bool) {
	if input.ID == "" {
		writeError(w, http.StatusBadRequest, "the client id is required")
		return domain.ClientData{}, false
	}

	redirectURIs, ok := validURLs(w, "redirect uri", input.RedirectURIs)
	if !ok {
		return domain.ClientData{}, false
	}

	postLogoutRedirectURIs, ok := validURLs(w, "post logout redirect uri", input.PostLogoutRedirectURIs)
	if !ok {
		return domain.ClientData{}, false
	}

	jwksURI := strings.TrimSpace(input.JWKSURI)
	if jwksURI != "" {
		if _, ok := validURLs(w, "jwks uri", []string{jwksURI}); !ok {
			return domain.ClientData{}, false
		}
	}

	var publicKeys []crypto.PublicKey
	for _, encoded := range input.PublicKeys {
		if strings.TrimSpace(encoded) == "" {
			continue
		}

		key, err := cryptography.ParsePublicKeyPEM([]byte(encoded))
		if err != nil {
			writeError(w, http.StatusBadRequest, "invalid public key: "+err.Error())
			return domain.ClientData{}, false
		}

		publicKeys = append(publicKeys, key)
	}

	return domain.ClientData{
		ID:                      input.ID,
		TokenEndpointAuthMethod: input.TokenEndpointAuthMethod,
		RedirectURIs:            redirectURIs,
		PostLogoutRedirectURIs:  postLogoutRedirectURIs,
		JWKSURI:                 jwksURI,
		PublicKeys:              publicKeys,
		GrantTypes:              input.GrantTypes,
	}, true
}

// grantTypes returns the grant types of the client (the defaults when it has none)
func grantTypes(data domain.ClientData) []string {
	if len(data.GrantTypes) == 0 {
		return append([]string{}, domain.DefaultGrantTypes...)
	}

	return append([]string{}, data.GrantTypes...)
}

// validURLs checks that the values are absolute URLs without fragment (RFC 6749 section 3.1.2)
func validURLs(w http.ResponseWriter, name string, values []string) ([]string, bool) {
	result := []string{}
	for _, value := range values {
		value = strings.TrimSpace(value)
		if value == "" {
			continue
		}

		u, err := url.Parse(value)
		if err != nil || !u.IsAbs() || u.Host == "" || u.Fragment != "" {
			writeError(w, http.StatusBadRequest, "invalid "+name+": "+value)
			return nil, false
		}

		result = append(result, value)
	}

	return result, true
}

func (h *Handler) deleteClient(w http.ResponseWriter, r *http.Request) {
	data, ok := h.findClient(w, r)
	if !ok {
		return
	}

	if err := h.grantStore.RevokeClient(data.ID); err != nil {
		writeInternalError(w, err)
		return
	}

	if err := h.clients.DeleteClient(data.ID); err != nil {
		writeStoreError(w, err)
		return
	}

	w.WriteHeader(http.StatusNoContent)
}

func (h *Handler) revokeClientTokens(w http.ResponseWriter, r *http.Request) {
	data, ok := h.findClient(w, r)
	if !ok {
		return
	}

	if err := h.grantStore.RevokeClient(data.ID); err != nil {
		writeInternalError(w, err)
		return
	}

	w.WriteHeader(http.StatusNoContent)
}
